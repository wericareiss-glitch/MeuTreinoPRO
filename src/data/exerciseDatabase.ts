// Carrega exercícios customizados persistidos no localStorage
export function loadPersistedCustomExercises(): void {
  try {
    const customList = safeStorage.get<Exercise[]>('mtp_custom_exercises', []);
    if (customList && customList.length > 0) {
      customList.forEach((customEx) => {
        const mKey = customEx.muscleKey;
        if (EXERCISE_DATABASE[mKey] && !EXERCISE_DATABASE[mKey].some((e) => e.id === customEx.id)) {
          EXERCISE_DATABASE[mKey].unshift(customEx);
        }
      });
    }
  } catch {
    // safe fallback
  }
}

// Inicializa custom exercises
loadPersistedCustomExercises();
